"""Builds the public results page (GitHub Pages) from results/results.json."""

from __future__ import annotations

import html
import json
from pathlib import Path

REPO = "https://github.com/mjsampsonmusic/caseworker"
CSS = """
:root{--ink:#1d2330;--muted:#5d6675;--line:#e3e6eb;--bg:#fbfbfc;--ok:#1f7a4d;--bad:#b3261e;--accent:#2f5bd3}
*{box-sizing:border-box}body{margin:0;font:15px/1.55 system-ui,-apple-system,Segoe UI,Roboto,sans-serif;color:var(--ink);background:var(--bg)}
main{max-width:1060px;margin:0 auto;padding:32px 20px 80px}h1{font-size:28px;margin:0 0 4px}h2{font-size:20px;margin:36px 0 10px}
p.lead{color:var(--muted)}a{color:var(--accent)}table{border-collapse:collapse;width:100%;background:#fff;border:1px solid var(--line);margin:8px 0}
th,td{padding:7px 10px;border-bottom:1px solid var(--line);text-align:left;vertical-align:top}th{background:#f3f5f8}td.num{text-align:right}
.small{font-size:13px;color:var(--muted)}details{background:#fff;border:1px solid var(--line);border-radius:8px;margin:8px 0;padding:10px 14px}
summary{cursor:pointer;font-weight:600}.ok{color:var(--ok)}.bad{color:var(--bad)}pre{white-space:pre-wrap;background:#f6f7f9;padding:10px;border-radius:6px;font-size:13px}
"""


def _e(value) -> str:
    return html.escape("" if value is None else str(value))


def _flag(ok: bool, yes: str, no: str) -> str:
    return f"<span class='{'ok' if ok else 'bad'}'>{_e(yes if ok else no)}</span>"


def build_site(results: dict, out_dir: Path) -> Path:
    run, s = results["run"], results["summary"]
    from .evaluate import summary_markdown  # reuse the same wording as the README table

    rows = [line.strip("|").split("|") for line in summary_markdown(results).splitlines() if line.startswith("| ")
            and not line.startswith("| |")]
    table = "".join(f"<tr><td>{_e(a.strip())}</td><td class='num'>{_e(b.strip())}</td></tr>" for a, b in rows)
    parts = [
        "<!doctype html><html lang='en'><head><meta charset='utf-8'><meta name='viewport' content='width=device-width,initial-scale=1'>",
        f"<title>caseworker evaluation</title><style>{CSS}</style></head><body><main><h1>caseworker evaluation</h1>",
        "<p class='lead'>A LangGraph agent working real consumer complaints end to end: triage with firstlook, rule "
        "lookups with fineprint, company history from SQL, a drafted letter checked by rules, a pause for human "
        f"approval, and a ticket in Case Router. Generated by GitHub Actions. <a href='{REPO}'>Code</a></p>",
        f"<p class='small'>Run finished {_e(run['finished'])} in {_e(run['minutes'])} minutes on {_e(run['machine'])}, "
        f"language model {_e(run['model'])}.</p>",
        f"<table><tbody>{table}</tbody></table>",
        f"<p class='small'>Average tokens per case: {_e(s['avg_input_tokens'])} in, {_e(s['avg_output_tokens'])} out. "
        f"Repeated tool calls across all cases: {_e(s['repeated_tool_calls'])}. Fallback searches: "
        f"{_e(s['fallback_searches'])}%.</p>",
        "<h2>Every case</h2>",
    ]
    for r in results["records"]:
        steps = " &rarr; ".join(f"{_e(t['step'])} ({t['ms'] / 1000:.1f} s): {_e(t['detail'])}" for t in r["trace"])
        parts.append(
            f"<details><summary>{_e(r['truth'])} | {_e(r['company'])} | "
            f"{_flag(r['triage_correct'], 'triage right', 'triage wrong')} | "
            f"{_flag(r['rule_family_match'], 'rule fits', 'rule does not fit')} | "
            f"{_flag(r['final_passed'], 'letter passed checks', 'letter failed checks')}</summary>"
            + (f"<p class='bad'>Error: {_e(r['error'])}</p>" if r["error"] else "")
            + f"<p class='small'>Bureau issue: {_e(r['issue'])}</p><p>{_e(r['text'])}</p>"
            f"<p class='small'>Triage: {_e(r['triage_product'])} at {_e(r['triage_confidence'])} ({_e(r['triage_route'])}). "
            f"Rules cited: {_e(', '.join(r['cited']) or 'none')}. Tool use: {_e(json.dumps(r['tool_use']))}. "
            f"Ticket queue: {_e(r['ticket_queue'])} (expected {_e(r['expected_queue'])}). Priority {_e(r['priority'])}.</p>"
            f"<p><b>Summary:</b> {_e(r['summary'])}</p><pre>{_e(r['letter'])}</pre>"
            + (f"<p class='small bad'>Remaining problems: {_e('; '.join(r['problems_final']))}</p>" if r["problems_final"] else "")
            + f"<p class='small'>Steps: {steps}<br>Tokens: {r['input_tokens']} in, {r['output_tokens']} out. "
            f"Time: {r['seconds']} s</p></details>")
    parts.append("<p class='small'>Complaint text comes from the CFPB's public archive of published narratives; the "
                 "bureau masked personal details before publishing. Letters are drafts for a caseworker, not legal "
                 "advice.</p></main></body></html>")
    out_dir.mkdir(parents=True, exist_ok=True)
    page = out_dir / "index.html"
    page.write_text("".join(parts))
    return page


def update_readme(readme: Path, summary: str) -> bool:
    start, end = "<!-- results:start -->", "<!-- results:end -->"
    text = readme.read_text()
    if start not in text or end not in text:
        return False
    before, rest = text.split(start, 1)
    _, after = rest.split(end, 1)
    readme.write_text(f"{before}{start}\n{summary}\n{end}{after}")
    return True
